def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--synthetic-runs", type=Path, default=DEFAULT_SYNTHETIC_RUNS)
    parser.add_argument("--mechanism-runs", type=Path, default=DEFAULT_MECHANISM_RUNS)
    parser.add_argument(
        "--out-dir",
        type=Path,
        default=ROOT / "docs/carsharing_tfm/final_thesis_pack_2026_06_02",
    )
    return parser.parse_args()


def main() -> None:
    args = parse_args()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    synthetic_rows = read_csv(args.synthetic_runs)
    mechanism_rows = read_csv(args.mechanism_runs)
    write_synthetic_tables(args.out_dir, synthetic_rows, mechanism_rows)
    munich_rows = write_munich_tables(args.out_dir, DEFAULT_MUNICH_SUMMARIES)
    write_markdown(args.out_dir, munich_rows)
    print(f"Wrote carsharing thesis artifacts to {args.out_dir}")


if __name__ == "__main__":
    main()
