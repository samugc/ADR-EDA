def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as handle:
        return list(csv.DictReader(handle))


def write_csv(path: Path, rows: list[dict[str, object]], fields: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow({field: row.get(field, "") for field in fields})


def f(row: dict[str, str], key: str) -> float:
    value = row.get(key, "")
    if value in {"", None}:
        return 0.0
    return float(value)


def fmt(value: float, digits: int = 2) -> str:
    return f"{value:.{digits}f}"


def mean_field(rows: Iterable[dict[str, str]], key: str) -> float:
    values = [f(row, key) for row in rows if row.get(key, "") not in {"", None}]
    return mean(values) if values else 0.0


def latex_escape(value: object) -> str:
    text = str(value)
    replacements = {
        "&": r"\&",
        "%": r"\%",
        "$": r"\$",
        "#": r"\#",
        "_": r"\_",
    }
    for old, new in replacements.items():
        text = text.replace(old, new)
    return text


def latex_table(
    path: Path,
    label: str,
    caption: str,
    headers: list[str],
    rows: list[list[object]],
    align: str,
) -> None:
    lines = [
        "% Auto-generated by scripts/build_carsharing_thesis_artifacts.py",
        r"\begin{table}[htbp]",
        r"\centering",
        r"\scriptsize",
        rf"\caption{{{latex_escape(caption)}}}",
        rf"\label{{{label}}}",
        r"\resizebox{\textwidth}{!}{%",
        rf"\begin{{tabular}}{{{align}}}",
        r"\toprule",
        " & ".join(latex_escape(header) for header in headers) + r" \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(" & ".join(latex_escape(value) for value in row) + r" \\")
    lines.extend([r"\bottomrule", r"\end{tabular}", "}", r"\end{table}", ""])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines), encoding="utf-8")


def summarize_variants(rows: list[dict[str, str]], labels: dict[str, str]) -> list[dict[str, object]]:
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[row["variant"]].append(row)

    out: list[dict[str, object]] = []
    for variant in labels:
        variant_rows = grouped.get(variant, [])
        if not variant_rows:
            continue
        out.append(
            {
                "policy": labels[variant],
                "n": len(variant_rows),
                "profit_eur": mean_field(variant_rows, "profit_eur"),
                "service_rate": mean_field(variant_rows, "service_rate"),
                "rejected": mean_field(variant_rows, "rejected_requests"),
                "drive_km": mean_field(variant_rows, "drive_km_total"),
                "deadhead_km": mean_field(variant_rows, "ops_deadhead_km_total"),
                "relocation_cost_eur": mean_field(variant_rows, "relocation_cost_eur"),
                "ops_cost_eur": mean_field(variant_rows, "ops_cost_eur"),
                "reopt": mean_field(variant_rows, "epochs_reoptimized"),
                "hold": mean_field(variant_rows, "epochs_hold"),
                "shift_l1": mean_field(variant_rows, "mean_shift_l1"),
            }
        )
    return out


def pairwise_delta(
    rows: list[dict[str, str]],
    lhs: str,
    rhs: str,
    label: str,
) -> dict[str, object]:
    by_variant_seed = {(row["variant"], row["seed"]): row for row in rows}
    seeds = sorted(
        {
            seed
            for variant, seed in by_variant_seed
            if variant == lhs and (rhs, seed) in by_variant_seed
        }
    )
    deltas = []
    for seed in seeds:
        left = by_variant_seed[(lhs, seed)]
        right = by_variant_seed[(rhs, seed)]
        deltas.append((left, right))

    def delta(key: str) -> float:
        return mean(f(left, key) - f(right, key) for left, right in deltas) if deltas else 0.0

    return {
        "comparison": label,
        "n": len(deltas),
        "delta_profit_eur": delta("profit_eur"),
        "delta_service_pp": 100.0 * delta("service_rate"),
        "delta_rejected": delta("rejected_requests"),
        "delta_deadhead_km": delta("ops_deadhead_km_total"),
        "delta_reopt": delta("epochs_reoptimized"),
        "profit_wins": sum(f(left, "profit_eur") > f(right, "profit_eur") for left, right in deltas),
        "service_nonworse": sum(f(left, "service_rate") >= f(right, "service_rate") for left, right in deltas),
        "deadhead_wins": sum(
            f(left, "ops_deadhead_km_total") < f(right, "ops_deadhead_km_total")
            for left, right in deltas
        ),
    }


def objective_snapshot(rows: list[dict[str, str]], variant: str, label: str) -> dict[str, object]:
    selected = []
    pareto_sizes = []
    reoptimized = 0
    total_records = 0
    for row in rows:
        if row["variant"] != variant:
            continue
        output_json = row.get("output_json", "")
        if not output_json:
            continue
        path = Path(output_json)
        if not path.exists() and str(path).startswith("/app/"):
            path = ROOT / str(path).removeprefix("/app/")
        if not path.exists():
            continue
        payload = json.loads(path.read_text(encoding="utf-8"))
        for item in payload.get("eda_fronts", {}).get("reoptimizations", []):
            total_records += 1
            if item.get("reoptimized"):
                reoptimized += 1
            objectives = item.get("selected_objectives") or []
            if len(objectives) == 3:
                selected.append(tuple(float(x) for x in objectives))
            pareto_size = item.get("pareto_size")
            if isinstance(pareto_size, (int, float)) and pareto_size > 0:
                pareto_sizes.append(float(pareto_size))

    return {
        "policy": label,
        "records": total_records,
        "reoptimized_records": reoptimized,
        "selected_f1_service": mean(values[0] for values in selected) if selected else 0.0,
        "selected_f2_profit": mean(values[1] for values in selected) if selected else 0.0,
        "selected_f3_health": mean(values[2] for values in selected) if selected else 0.0,
        "pareto_size": mean(pareto_sizes) if pareto_sizes else 0.0,
    }


def summarize_munich(label: str, path: Path) -> dict[str, object]:
    rows = read_csv(path)
    grouped: dict[str, list[dict[str, str]]] = defaultdict(list)
    for row in rows:
        grouped[row["mode"]].append(row)

    baseline = grouped["baseline"]
    adr = grouped["online_adr_eda"]
    static = grouped.get("static_eda", [])
    requests = mean_field(adr or baseline, "requests")
    baseline_service = mean_field(baseline, "service_rate")
    adr_service = mean_field(adr, "service_rate")
    baseline_profit = mean_field(baseline, "comparable_profit_eur")
    adr_profit = mean_field(adr, "comparable_profit_eur")
    baseline_km = mean_field(baseline, "drive_km_total")
    adr_km = mean_field(adr, "drive_km_total")

    return {
        "campaign": label,
        "n": len(adr),
        "requests": requests,
        "baseline_service": baseline_service,
        "adr_service": adr_service,
        "delta_service_pp": 100.0 * (adr_service - baseline_service),
        "baseline_profit": baseline_profit,
        "adr_profit": adr_profit,
        "delta_profit": adr_profit - baseline_profit,
        "delta_km": adr_km - baseline_km,
        "adr_reopts": mean_field(adr, "eda_reopt_count"),
        "adr_runtime_sec": mean_field(adr, "runtime_sec"),
        "adr_f1": mean_field(adr, "f1_service"),
        "adr_f2": mean_field(adr, "f2_profit"),
        "adr_f3": mean_field(adr, "f3_health"),
        "static_pareto_size": mean_field(static, "pareto_size") if static else 0.0,
        "online_pareto_size": mean_field(adr, "pareto_size"),
        "path": str(path),
    }


